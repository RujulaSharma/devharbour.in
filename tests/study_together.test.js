const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const express=require('express');
const {PGlite}=require('@electric-sql/pglite');

test('private groups, timer presence and session recovery across two accounts',async t=>{
  const pg=new PGlite();
  await pg.exec("CREATE ROLE anon;CREATE ROLE authenticated;CREATE TABLE users(id text PRIMARY KEY,username text); INSERT INTO users VALUES ('a','Alex'),('b','Bela'),('c','Cam');");
  await pg.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261124160000_study_together.sql'),'utf8'));
  const conn={query:(sql,params)=>pg.query(sql,params),release(){}};
  const db=require('../server/db-postgres');
  const awards=new Set();
  t.mock.method(db,'awardXp',async(user,amount,type,reference)=>{
    const key=user+reference,awarded=!awards.has(key);awards.add(key);return {amount,awarded};
  });
  db.pool={...conn,connect:async()=>conn};
  const app=express();
  app.use(express.json());
  app.use((req,res,next)=>{const id=req.headers['x-test-user'];if(id)req.user={id,username:id,emailVerified:true};next();});
  app.use('/study',require('../server/routes/study'));
  const server=app.listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await pg.close();});
  const request=async(user,route,body,status=200)=>{
    const headers={'Content-Type':'application/json'};
    if(user) headers['x-test-user']=user;
    const res=await fetch('http://127.0.0.1:'+server.address().port+'/study/'+route,{method:body?'POST':'GET',headers,body:JSON.stringify(body)});
    const data=await res.json();assert.equal(res.status,status,JSON.stringify(data));return data;
  };
  await request(null,'state',undefined,401);
  await request('a','group',{action:'create',name:'Evening study'});
  const {invite}= (await request('a','state')).group;
  await request('b','group',{action:'join',invite});
  const started=await request('a','timer',{action:'start',duration:1500,subject:'Math'});
  const id=started.session.id;
  assert.equal((await request('a','timer',{action:'start',duration:300})).session.id,id);
  let friend=await request('b','state');
  assert.equal(friend.active,1);assert.equal(friend.group.starts.length,1);
  assert.equal(friend.group.members.find(m=>m.id==='a').status,'Studying');
  assert.equal(friend.group.invite,null);
  assert.equal((await request('c','state')).group,null);
  await request('c','timer',{action:'pause',id},404);
  await request('b','group',{action:'mute',value:true});
  assert.deepEqual((await request('b','state')).group.starts,[]);
  await request('a','timer',{action:'pause',id});
  assert.equal((await request('b','state')).group.members.find(m=>m.id==='a').status,'On break');
  assert.equal((await request(null,'count')).active,0);
  await request('a','timer',{action:'resume',id});
  await pg.query("UPDATE study_together.sessions SET touched=now()-interval '5 minutes' WHERE id=$1",[id]);
  assert.equal((await request(null,'count')).active,0);
  assert.equal((await request('a','timer',{action:'pulse',id})).session.state,'paused');
  await request('a','timer',{action:'resume',id});
  await pg.query("UPDATE study_together.sessions SET elapsed=1499,touched=now()-interval '2 seconds' WHERE id=$1",[id]);
  assert.equal((await request('a','timer',{action:'pulse',id})).reward.awarded,true);
  assert.equal((await request('a','timer',{action:'pulse',id})).reward,null);
  const result=await request('a','state');
  assert.equal(result.totals.seconds,1500);assert.equal(result.totals.streak,1);
  assert.equal(result.history[0].subject,'Math');assert.equal(result.session,null);
  await request('a','group',{action:'remove',member:'b'});
  assert.equal((await request('b','state')).group,null);
  await request('b','group',{action:'join',invite},404);
});

const { test, expect } = require('@playwright/test');
async function signup(page, email, expectEmail = true) {
  await page.goto('/');
  if (page.viewportSize().width <= 800) {
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
    await page.locator('#dh-homepage .mobile-menu').getByRole('link', { name: 'Get Started', exact: true }).click();
  } else await page.locator('#dh-homepage .nav-btn').click();
  await page.locator('#su-name').fill('Browser Certificate Fixture');
  await page.locator('#su-user').fill('mailbox_' + Date.now()); await page.locator('#su-email').fill(email);
  await page.locator('#su-pass').fill('Browser-fixture-password-7!');
  await page.locator('#form-signup button[type=submit]').click();
  await expect(page.locator('#v-home')).toHaveClass(/on/);
  await expect(page.locator('#intro')).toHaveClass(/out/);
  if (expectEmail) await expect(page.locator('#my-certificates')).toContainText(email);
}
test('verified participant can view, download, and share their existing certificate; logout removes access', async ({ page }) => {
  test.setTimeout(60000);
  await signup(page, 'mailbox-fixture@example.test');
  const card = page.locator('#my-certificates');
  expect((await page.request.get('/api/certificates/mine')).status()).toBe(403);
  await card.getByRole('button', { name: 'Send verification code', exact: true }).click();
  await expect(card).toContainText('Code sent.');
  await card.getByLabel('Six-digit verification code').fill('000000');
  await card.getByRole('button', { name: 'Verify email', exact: true }).click();
  await expect(card).toContainText('Incorrect verification code.');
  await card.getByLabel('Six-digit verification code').fill('482915');
  await card.getByRole('button', { name: 'Verify email', exact: true }).click();
  await expect(card).toContainText('Browser Certificate Fixture');
  const mine = await (await page.request.get('/api/certificates/mine')).json();
  expect(mine.certificates).toHaveLength(1);
  await page.locator('#dh-platform-navigation .nav-links').getByRole('link', { name: 'Workspace', exact: true }).click();
  await page.locator('#dh-platform-navigation .nav-links').getByRole('link', { name: 'Certificates', exact: true }).click();
  await expect(card).toContainText('Browser Certificate Fixture');
  await expect(page.locator('#dh-auth-modal')).not.toHaveClass(/open/);
  await expect(page.locator('#dh-cert-lock-modal')).toHaveCount(0);
  const before = await (await page.request.get('/api/certificates/stats')).json();
  const downloadEvent = page.waitForEvent('download');
  await card.getByRole('button', { name: 'Download SVG', exact: true }).click();
  const download = await downloadEvent; expect(download.suggestedFilename()).toMatch(/^DH-ORCA-2026-.*\.svg$/);
  await download.saveAs(test.info().outputPath('own-certificate.svg'));
  await card.getByRole('button', { name: 'View certificate', exact: true }).click();
  const dialog = page.getByRole('dialog'); await expect(dialog).toBeVisible();
  await expect(dialog.locator('svg')).toContainText('BROWSER CERTIFICATE FIXTURE');
  await page.screenshot({ path: test.info().outputPath('verified-certificate.png'), fullPage: false });
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  const link = card.getByRole('link', { name: 'Verify certificate', exact: true });
  const verification = await page.request.get(await link.getAttribute('href'));
  expect(verification.ok()).toBe(true);
  const publicPage = await page.context().browser().newPage();
  await publicPage.goto(await link.getAttribute('href'));
  await expect(publicPage.locator('#dh-cert-stage')).toBeVisible();
  await expect(publicPage.locator('#dh-cert-svg-slot')).toContainText('BROWSER CERTIFICATE FIXTURE');
  await expect(publicPage.locator('#dh-auth-modal')).not.toHaveClass(/open/);
  await expect(publicPage.locator('#dh-cert-lock-modal')).toHaveCount(0);
  await publicPage.close();
  await card.getByRole('button', { name: 'Copy verification link' }).click();
  await expect(card).toContainText(/Link copied|Copy verification link/);
  await page.reload(); await expect(card).toContainText('Browser Certificate Fixture');
  const after = await (await page.request.get('/api/certificates/stats')).json();
  expect(after.totalIssued).toBe(before.totalIssued);
  await page.evaluate(() => window.handleLogout());
  await expect(card).not.toContainText('Browser Certificate Fixture');
  expect((await page.request.get('/api/certificates/mine')).status()).toBe(401);
});
test('verified unmatched account sees guidance and verification fits mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await signup(page, 'unmatched_' + Date.now() + '@example.test');
  const card = page.locator('#my-certificates');
  await card.getByRole('button', { name: 'Send verification code', exact: true }).click();
  await expect(card).toContainText('Code sent.');
  await card.getByLabel('Six-digit verification code').fill('482915');
  await card.getByRole('button', { name: 'Verify email', exact: true }).click();
  await expect(card).toContainText('No eligible registration matches');
  await expect(card.locator('article')).toHaveCount(0);
  const bounds = await card.boundingBox(); expect(bounds.x + bounds.width).toBeLessThanOrEqual(391);
  await page.screenshot({ path: test.info().outputPath('unmatched-mobile.png'), fullPage: false });
});
test('verification service outage displays retry and does not expose certificates', async ({ page }) => {
  await page.route('**/api/auth/email-verification', route => route.fulfill({ status: 503, json: { error: 'Verification temporarily unavailable.' } }));
  await signup(page, 'outage_' + Date.now() + '@example.test', false);
  const card = page.locator('#my-certificates');
  await expect(card).toContainText('Verification temporarily unavailable.');
  await expect(card.getByRole('button', { name: 'Retry', exact: true })).toBeVisible();
  await expect(card.locator('article')).toHaveCount(0);
});

test('navbar Certificates asks guests to sign in and returns them to their own certificate dashboard', async ({ page }) => {
  await page.goto('/');
  await page.locator('#dh-homepage .nav-links').getByRole('link', { name: 'Dashboard', exact: true }).click();
  await page.locator('#dh-platform-navigation .nav-links').getByRole('link', { name: 'Certificates', exact: true }).click();
  await expect(page.locator('#dh-auth-modal')).toHaveClass(/open/);
  await expect(page.locator('#form-login')).toBeVisible();
  await expect(page.locator('#dh-cert-lock-modal')).toHaveCount(0);
  await page.evaluate(() => window.switchAuthTab('signup'));
  await page.locator('#su-name').fill('Sidebar Certificate Fixture');
  await page.locator('#su-user').fill('sidebar_' + Date.now());
  await page.locator('#su-email').fill('sidebar_' + Date.now() + '@example.test');
  await page.locator('#su-pass').fill('Sidebar-fixture-password-7!');
  await page.locator('#form-signup button[type=submit]').click();
  await expect(page.locator('#dh-auth-modal')).not.toHaveClass(/open/);
  await expect(page.locator('#my-certificates')).toContainText('Verify sidebar_');
  await expect(page.locator('#my-certificates input[name=code]')).toBeVisible();
  expect((await page.request.get('/api/certificates/mine')).status()).toBe(403);
});
